#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
clean_ai_traces.py — AIGC 痕迹自动清理 + 清理后自动重扫（强制闭环）
用法:
    python clean_ai_traces.py <文件或目录> [--report <输出报告路径>]
策略:
    .md/.txt: 删除整行仅含 AIGC 标注变体的行（删除前会列出被删行）
    .docx  : 解包 word/document.xml，删除仅含标注文本的 <w:t> 节点；
             若段落 <w:p> 无任何可见文本则整段删除；重打包保持其余结构
清理完成后自动调用扫描逻辑重扫，命中 0 才退出 0，否则退出 1（禁止交付）。
"""
import sys, os, re, zipfile, json, shutil
from pathlib import Path

VARIANTS = [
    "AI生成", "AI 生成", "ai生成", "内容由AI生成", "内容由 AI 生成",
    "由AI创作", "由 AI 创作", "AIGC", "AI写作", "AI 写作",
    "人工智能生成", "智能助手生成", "生成于AI", "生成于 AI", "AI辅助", "AI 辅助",
    "ContentProducer", "content producer", "Generated by AI", "generated by AI",
    "Generated with AI", "Generated using AI", "Produced by AI", "Made with AI",
    "AI-generated", "ai generated", "ChatGPT", "GPT-4", "Claude", "Copilot",
    "DeepSeek", "LLM-generated", "llm generated",
    "仅供参考", "内容由AI生成仅供学习", "本文由AI生成", "以上内容由AI生成",
    "如有雷同纯属AI", "番茄AI标注", "七猫AI标注", "AIGC标注",
]

def norm(s):
    return re.sub(r"\s+", "", s) if s else ""

def line_is_pure_variant(line):
    """整行去掉空白/标点/装饰符号后，剩余内容完全由变体关键词组成。
    支持多变体串联（如 '内容由AI生成，仅供参考' 拆为两个变体）与逗号分隔。"""
    cleaned = norm(line).strip()
    cleaned = cleaned.strip("*#|>-—·（(【['\"")
    if not cleaned:
        return False
    punct = "，。、；：！？（）()【】[]{}《》〈〉\"\"''「」『』…—·-*#|> \t.。·~～"
    # 长变体优先匹配（避免 "AIGC" 抢先吃掉 "AIGC标注"）
    variants_sorted = sorted([v for v in VARIANTS if norm(v)], key=lambda x: len(norm(x)), reverse=True)
    while cleaned:
        matched = False
        for v in variants_sorted:
            vn = norm(v)
            if cleaned.startswith(vn):
                cleaned = cleaned[len(vn):].lstrip(punct)
                matched = True
                break
        if not matched:
            return False
    return True

def clean_text_file(path: Path):
    with open(path, "r", encoding="utf-8", errors="ignore") as f:
        lines = f.readlines()
    removed, kept = [], []
    for line in lines:
        if line_is_pure_variant(line):
            removed.append(line.strip())
        else:
            kept.append(line)
    if removed:
        # 保留原换行风格
        with open(path, "w", encoding="utf-8") as f:
            f.writelines(kept)
    return removed

def clean_docx(path: Path):
    """解包 docx，清理 document.xml 中的标注节点，重打包。返回删除段落数。"""
    tmp = path.with_suffix(path.suffix + ".tmp")
    try:
        with zipfile.ZipFile(path) as zin:
            items = {n: zin.read(n) for n in zin.namelist()}
    except Exception as e:
        print(f"[ERROR] docx 解包失败 {path}: {e}")
        sys.exit(2)
    removed_paras = 0
    for name, data in items.items():
        if not name.startswith("word/") or not name.endswith(".xml"):
            continue
        xml = data.decode("utf-8", errors="ignore")
        orig = xml
        # 1) 删除仅含标注文本的 <w:t> 节点
        def repl(m):
            txt = m.group(1)
            if txt and line_is_pure_variant(txt):
                return ""  # 删除节点
            return m.group(0)
        xml = re.sub(r"<w:t[^>]*>([^<]*)</w:t>", repl, xml)
        # 2) 删除无任何可见文本的 <w:p> 段落（仅含格式节点）
        removed_now = [0]
        def repl_para(m):
            if not re.search(r"<w:t[^>]*>[^<]+</w:t>", m.group(0)):
                removed_now[0] += 1
                return ""
            return m.group(0)
        xml = re.sub(r"<w:p[^>]*>(?:(?!</w:p>).)*?</w:p>", repl_para, xml, flags=re.S)
        removed_paras += removed_now[0]
        items[name] = xml.encode("utf-8")
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
        for n, d in items.items():
            zout.writestr(n, d)
    shutil.move(str(tmp), str(path))
    return removed_paras

# ---- 复用扫描逻辑做清理后自动重扫 ----
def rescan(target: Path):
    files = []
    if target.is_file():
        files = [target]
    elif target.is_dir():
        files = [p for p in target.rglob("*") if p.is_file() and p.suffix.lower() in (".txt", ".md", ".docx")]
    hits = []
    for f in sorted(files):
        if f.suffix.lower() == ".docx":
            try:
                with zipfile.ZipFile(f) as z:
                    xmls = [n for n in z.namelist() if n.startswith("word/") and n.endswith(".xml")]
                    for n in xmls:
                        txts = re.findall(r"<w:t[^>]*>(.*?)</w:t>", z.read(n).decode("utf-8", errors="ignore"), flags=re.S)
                        joined = "".join(txts)
                        for v in VARIANTS:
                            if norm(v) and norm(v) in norm(joined):
                                hits.append(f"{f.name}:{n}:{v.strip()}")
            except Exception:
                continue
        else:
            try:
                with open(f, "r", encoding="utf-8", errors="ignore") as fh:
                    for lineno, line in enumerate(fh, 1):
                        for v in VARIANTS:
                            if norm(v) and norm(v) in norm(line):
                                hits.append(f"{f.name}:{lineno}:{v.strip()}")
            except Exception:
                continue
    return files, hits

def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    target = Path(sys.argv[1])
    report_path = None
    if "--report" in sys.argv:
        i = sys.argv.index("--report")
        if i + 1 < len(sys.argv):
            report_path = Path(sys.argv[i + 1])
    if not target.exists():
        print(f"[ERROR] 路径不存在: {target}")
        sys.exit(2)

    files = [target] if target.is_file() else [p for p in target.rglob("*") if p.is_file() and p.suffix.lower() in (".txt", ".md", ".docx")]
    total_removed_lines, total_removed_paras = 0, 0
    print("=" * 50)
    print("AIGC 痕迹自动清理")
    for f in sorted(files):
        if f.suffix.lower() == ".docx":
            n = clean_docx(f)
            total_removed_paras += n
            if n:
                print(f"  [docx] {f.name}: 删除标注段落 {n}")
        else:
            removed = clean_text_file(f)
            if removed:
                total_removed_lines += len(removed)
                print(f"  [文本] {f.name}: 删除标注行 {len(removed)}")
                for r in removed:
                    print(f"      - {r}")
    print("-" * 50)
    print("清理后自动重扫...")
    scan_files, hits = rescan(target)
    print(f"扫描文件数: {len(scan_files)}  剩余命中: {len(hits)}")
    for h in hits[:50]:
        print(f"  [残留] {h}")
    print("=" * 50)
    if report_path:
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(json.dumps({
            "scope": str(target), "removed_lines": total_removed_lines,
            "removed_paras": total_removed_paras, "rescan_hits": hits
        }, ensure_ascii=False, indent=2), encoding="utf-8")
    if hits:
        print("结论: 仍有残留，禁止交付。")
        sys.exit(1)
    print(f"结论: 清理完成（删标注行 {total_removed_lines}，删标注段 {total_removed_paras}），零残留通过。")
    sys.exit(0)

if __name__ == "__main__":
    main()
